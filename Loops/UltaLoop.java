package Loops;

public class UltaLoop {
    static void main() {
        for(int i=10;i>=1;i-=1){
            System.out.print(i+" ");
        }

        for(int i=19;i<=190;i+=19){
            System.out.print(i+" ");
        }

        for(int i=1;i<=10;i++){
            System.out.print(19*i+" ");
        }
    }
}
