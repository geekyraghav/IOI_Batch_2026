package BasicsOfJava;

public class UpdatingVariables {
    static void main() {
        int x = 10;
        System.out.println(x);
        x += 9; // x = x + 9
        System.out.println(x);
        x = x - 2; // x = 17
        System.out.println(x);
        x *= 3; // x = 51
        System.out.println(x);
    }
}

